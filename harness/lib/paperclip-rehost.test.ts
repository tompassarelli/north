import { test, expect } from "bun:test";
import { Database } from "bun:sqlite";
import { mkdtempSync, mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

test("recorded rehost cutover preserves issue identities and SOC children across number collisions", () => {
  const evidence = join(import.meta.dir, "../../target/paperclip-rehost-evidence");
  mkdirSync(evidence, { recursive: true });
  const root = mkdtempSync(join(evidence, "cutover-"));
  const path = join(root, "state.db");
  const db = new Database(path);
  db.exec("CREATE TABLE sync_meta(key TEXT PRIMARY KEY,value TEXT NOT NULL); CREATE TABLE sync_objects(key TEXT PRIMARY KEY,kind TEXT NOT NULL,id TEXT NOT NULL,fields TEXT NOT NULL); CREATE TABLE paperclip_decisions(source_key TEXT PRIMARY KEY,data TEXT NOT NULL)");
  const rows = [["smashcraft#563", "soc"], ["smashcraft#346", "live-one"], ["smashcraft#1", "closed-one"], ["smashcraft#17", "closed-seventeen"], ["wisp#119", "wisp-live"], ["wisp#1", "wisp-closed"], ["north#8", "north-untouched"]];
  for (let n = 550; n <= 555; n++) rows.push([`smashcraft#${n}`, `child-${n}`]);
  const issues = rows.map(([ref, id]) => ({ key: `gh:${ref}`, ref, id, ...(ref.startsWith("smashcraft#55") ? { parentKey: "gh:smashcraft#563" } : {}) }));
  for (const issue of issues) db.query("INSERT INTO sync_objects VALUES (?,'issues',?,?)").run(issue.key, issue.id, JSON.stringify({ parentId: issue.parentKey ? "soc" : null }));
  db.query("INSERT INTO sync_meta VALUES ('desired',?)").run(JSON.stringify({ projects: [], issues, trackedRefs: issues.map(i => i.ref) }));
  db.query("INSERT INTO sync_meta VALUES ('github',?)").run(JSON.stringify(issues.map(i => ({ ref: i.ref, url: `https://github.com/tompassarelli/${i.ref.split("#")[0]}/issues/${i.ref.split("#")[1]}`, parent: i.parentKey?.slice(3), subissues: i.id === "soc" ? issues.filter(c => c.parentKey).map(c => c.ref) : [] }))));
  db.query("INSERT INTO paperclip_decisions VALUES (?,?)").run("gh:smashcraft#346", JSON.stringify({ targetKey: "gh:smashcraft#563" }));
  db.query("INSERT INTO paperclip_decisions VALUES (?,?)").run("gh:smashcraft#1", JSON.stringify({ targetKey: "gh:smashcraft#1" }));
  db.close();
  const cli = (...args: string[]) => Bun.spawnSync(["bun", join(import.meta.dir, "../../bin/paperclip-sync"), ...args], { env: { ...process.env, PAPERCLIP_SYNC_STATE_DIR: root }, stdout: "pipe", stderr: "pipe" });
  const invoke = (...args: string[]) => {
    const result = cli(...args);
    expect(result.stderr.toString()).toBe("");
    expect(result.exitCode).toBe(0);
    return JSON.parse(result.stdout.toString());
  };
  expect(invoke("pause", "smashcraft", "wisp")).toEqual(["smashcraft", "wisp"]);
  expect(invoke("pauses")).toEqual(["smashcraft", "wisp"]);
  const smashMap = join(root, "smashcraft.tsv");
  const wispMap = join(root, "wisp.tsv");
  writeFileSync(smashMap, "346\t1\tlive one\n563\t17\tSOC\n" + Array.from({ length: 6 }, (_, i) => `${550 + i}\t${7 + i}\tchild\n`).join(""));
  writeFileSync(wispMap, "119\t1\twisp live\n");
  expect(invoke("rekey", "smashcraft", smashMap, join(root, "smash-backup.db"))).toMatchObject({ moved: 8, archived: 2, repeated: false });
  expect(invoke("rekey", "wisp", wispMap, join(root, "wisp-backup.db"))).toMatchObject({ moved: 1, archived: 1 });
  const migrated = new Database(path, { readonly: true });
  const identity = (key: string) => (migrated.query("SELECT id FROM sync_objects WHERE key=?").get(key) as { id: string }).id;
  expect(identity("gh:smashcraft#1")).toBe("live-one");
  expect(identity("gh:smashcraft#17")).toBe("soc");
  expect(identity("rehost:gh:smashcraft#1")).toBe("closed-one");
  expect(identity("rehost:gh:smashcraft#17")).toBe("closed-seventeen");
  expect(identity("gh:wisp#1")).toBe("wisp-live");
  expect(identity("gh:north#8")).toBe("north-untouched");
  for (let n = 7; n <= 12; n++) {
    const row = migrated.query("SELECT id,fields FROM sync_objects WHERE key=?").get(`gh:smashcraft#${n}`) as { id: string; fields: string };
    expect(row.id).toBe(`child-${n + 543}`);
    expect(JSON.parse(row.fields).parentId).toBe("soc");
  }
  const desired = JSON.parse((migrated.query("SELECT value FROM sync_meta WHERE key='desired'").get() as { value: string }).value);
  expect(desired.issues.find((i: any) => i.id === "child-550")).toMatchObject({ key: "gh:smashcraft#7", ref: "smashcraft#7", parentKey: "gh:smashcraft#17" });
  expect(desired.trackedRefs).not.toContain("smashcraft#563");
  expect(desired.issues.some((i: any) => i.id === "closed-one")).toBe(false);
  const github = JSON.parse((migrated.query("SELECT value FROM sync_meta WHERE key='github'").get() as { value: string }).value);
  expect(github.find((i: any) => i.ref === "smashcraft#7")).toMatchObject({ parent: "smashcraft#17", url: "https://github.com/tompassarelli/smashcraft/issues/7" });
  expect(migrated.query("SELECT source_key FROM paperclip_decisions WHERE source_key='gh:smashcraft#1'").get()).not.toBeNull();
  const beforeRepeat = JSON.stringify(migrated.query("SELECT * FROM sync_objects ORDER BY key").all());
  migrated.close();
  expect(invoke("rekey", "smashcraft", smashMap, join(root, "repeat-backup.db"))).toMatchObject({ repeated: true });
  const repeated = new Database(path, { readonly: true });
  expect(JSON.stringify(repeated.query("SELECT * FROM sync_objects ORDER BY key").all())).toBe(beforeRepeat);
  repeated.close();
  const backup = new Database(join(root, "smash-backup.db"), { readonly: true });
  expect((backup.query("SELECT id FROM sync_objects WHERE key='gh:smashcraft#1'").get() as { id: string }).id).toBe("closed-one");
  backup.close();
  expect(invoke("resume", "smashcraft")).toEqual(["wisp"]);
  expect(cli("rekey", "smashcraft", smashMap, join(root, "unpaused-backup.db")).exitCode).toBe(1);
  expect(invoke("resume", "wisp")).toEqual([]);
});
