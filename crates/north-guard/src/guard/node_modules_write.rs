use super::handoff_record::edited_paths;
use crate::hook::{HookInput, Verdict};
use crate::shell::{ShellToken, basename, operator_tokens, strip_heredoc_bodies};
use std::path::Path;

pub fn evaluate(input: &HookInput) -> Verdict {
    if crate::guard::activation::authoring_guards_off("north-hook") {
        return Verdict::Allow;
    }
    decide(input)
}

pub(super) fn decide(input: &HookInput) -> Verdict {
    let targets = if input.is_shell() {
        input.command().map(|command| shell_targets(&command.lossy())).unwrap_or_default()
    } else if matches!(input.tool_name(), "Edit" | "Write" | "MultiEdit" | "NotebookEdit" | "apply_patch") {
        edited_paths(input)
    } else {
        Vec::new()
    };
    match targets.into_iter().find(|path| installed(path)) {
        Some(path) => Verdict::Deny(denial(&path)),
        None => Verdict::Allow,
    }
}

fn installed(path: &str) -> bool {
    Path::new(path).components().any(|part| part.as_os_str() == "node_modules")
}

fn denial(path: &str) -> String {
    format!(
        "node-modules-write: `{path}` is inside node_modules/. Bun installs node_modules as hard links into its global cache, so this write changes the same file in every checkout of that package version, including other agents' worktrees and Tom's build watcher. Change the vendored source in its own repository and re-pin, or copy the package out of node_modules first (cp -r --no-preserve=links) and edit the copy."
    )
}

fn shell_targets(command: &str) -> Vec<String> {
    let Ok(tokens) = operator_tokens(&strip_heredoc_bodies(command)) else {
        return Vec::new();
    };
    let mut targets = Vec::new();
    let mut teeing = false;
    for (at, token) in tokens.iter().enumerate() {
        match token {
            ShellToken::Operator(operator) if matches!(operator.as_str(), ">" | ">>") => {
                teeing = false;
                if let Some(ShellToken::Word(target)) = tokens.get(at + 1) {
                    targets.push(target.clone());
                }
            }
            ShellToken::Operator(_) => teeing = false,
            ShellToken::Word(word) if teeing && !word.starts_with('-') => targets.push(word.clone()),
            ShellToken::Word(word) => teeing |= basename(word) == "tee",
        }
    }
    targets
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    const APPENDED: &str = "node_modules/wisp/window/wisp-window/src/lib.rs";

    fn call(tool: &str, input: serde_json::Value) -> HookInput {
        let payload = json!({
            "tool_name": tool,
            "cwd": "/home/tom/code/smashcraft/worktrees/sc-prebuild-lib",
            "tool_input": input,
        });
        HookInput::parse(&serde_json::to_vec(&payload).unwrap()).unwrap()
    }

    fn refused(input: &HookInput) -> bool {
        match decide(input) {
            Verdict::Deny(reason) => {
                assert!(reason.contains("hard links into its global cache"), "{reason}");
                assert!(reason.contains("re-pin") && reason.contains("copy the package"), "{reason}");
                true
            }
            Verdict::Allow => false,
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn the_2026_10_31_append_to_an_installed_wisp_source_is_refused() {
        let append = format!("printf '\\n#[test]\\nfn prebuild_probe() {{}}\\n' >> {APPENDED}");
        assert!(refused(&call("Bash", json!({"command": append}))));
        let heredoc = format!("cat >> {APPENDED} <<'EOF'\n#[test]\nfn prebuild_probe() {{}}\nEOF");
        assert!(refused(&call("Bash", json!({"command": heredoc}))));
    }

}
