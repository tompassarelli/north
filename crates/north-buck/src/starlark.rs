use std::fmt::Write;

use crate::plan::{Buckfile, Rule, RuleKind};
use crate::sources::{Export, Tree};

pub const HEADER: &str = "# @generated by `north buck targets` from the Cargo manifests; edit those and rerun it.";

const LOAD: &str = "load(\"//build:rust_test.bzl\", \"manifest_dir_flags\", \"north_files\", \"north_rust_test\")";
const ROOT_LOAD: &str = "load(\"//build:rust_test.bzl\", \"manifest_dir_flags\", \"north_files\", \"north_rust_test\", \"north_tree\")";

/// Buck2's `**` skips a name that starts with a dot, and tests read `.safe-push` and `.cargo/config.toml`.
const FILES: [&str; 3] = ["**", "**/.*", "**/.*/**"];
const ROOT_EXCLUDES: [&str; 6] = [".buckconfig.flake", ".git", "buck-out/**", "crates/**", "target/**", "worktrees/**"];

pub fn render(file: &Buckfile) -> String {
    let mut out = format!("{HEADER}\n\n{}\n", if file.tree.is_empty() { LOAD } else { ROOT_LOAD });
    if !file.features.is_empty() {
        out.push_str(&format!("\nFEATURES = {}\n", list(&file.features, 0)));
    }
    out.push_str(&format!("\nRUSTC_FLAGS = {}\n", list(&file.rustc_flags, 0)));
    for rule in &file.rules {
        out.push('\n');
        render_rule(&mut out, rule, !file.features.is_empty());
    }
    out.push('\n');
    files(&mut out, file.dir.is_empty());
    if !file.tree.is_empty() {
        let _ = writeln!(out, "\nnorth_tree(\n    name = \"tree\",\n    parts = {},\n    visibility = [\"PUBLIC\"],\n)", list(&file.tree, 1));
    }
    for export in &file.exports {
        out.push('\n');
        match export {
            Export::File(path) => {
                let _ = writeln!(out, "export_file(\n    name = {},\n    visibility = [\"PUBLIC\"],\n)", quote(path));
            }
            Export::Dir(path) => {
                let inside = format!("{path}/");
                let _ = writeln!(
                    out,
                    "filegroup(\n    name = {},\n    srcs = {{path[{}:]: path for path in glob([{}])}},\n    visibility = [\"PUBLIC\"],\n)",
                    quote(path),
                    inside.len(),
                    quote(&format!("{path}/**"))
                );
            }
        }
    }
    out
}

fn render_rule(out: &mut String, rule: &Rule, features: bool) {
    let function = match rule.kind {
        RuleKind::Library | RuleKind::ProcMacro => "rust_library",
        RuleKind::Binary => "rust_binary",
        RuleKind::Test => "north_rust_test",
    };
    let _ = writeln!(out, "{function}(");
    let _ = writeln!(out, "    name = {},", quote(&rule.name));
    if let Some(binary_id) = &rule.binary_id {
        let _ = writeln!(out, "    binary_id = {},", quote(binary_id));
    }
    sources(out, &rule.tree);
    let _ = writeln!(out, "    crate = {},", quote(&rule.crate_name));
    let _ = writeln!(out, "    crate_root = {},", quote(&rule.crate_root));
    let _ = writeln!(out, "    edition = {},", quote(&rule.edition));
    if features {
        out.push_str("    features = FEATURES,\n");
    }
    out.push_str(if rule.kind == RuleKind::Test { "    rustc_flags = RUSTC_FLAGS,\n" } else { "    rustc_flags = manifest_dir_flags() + RUSTC_FLAGS,\n" });
    if rule.kind == RuleKind::ProcMacro {
        out.push_str("    proc_macro = True,\n");
    }
    if !rule.env.is_empty() {
        let _ = writeln!(out, "    env = {},", dict(rule.env.iter(), 1));
    }
    if !rule.run_env.is_empty() {
        let _ = writeln!(out, "    run_env = {},", dict(rule.run_env.iter(), 1));
    }
    if !rule.resources.is_empty() {
        let _ = writeln!(out, "    resources = {},", list(&rule.resources, 1));
    }
    if !rule.deps.is_empty() {
        let _ = writeln!(out, "    deps = {},", list(&rule.deps, 1));
    }
    if !rule.named_deps.is_empty() {
        let _ = writeln!(out, "    named_deps = {},", dict(rule.named_deps.iter(), 1));
    }
    out.push_str("    visibility = [\"PUBLIC\"],\n)\n");
}

fn sources(out: &mut String, tree: &Tree) {
    let globbed = format!("glob({})", inline(&tree.globs));
    let files = if tree.extras.is_empty() { globbed } else { format!("{globbed} + {}", inline(&tree.extras)) };
    let foreign = (!tree.foreign.is_empty()).then(|| dict(tree.foreign.iter(), 1));
    match (&tree.prefix, foreign) {
        (Some(prefix), foreign) => {
            let mapped = format!("{{path: {} + path for path in {files}}}", quote(&format!("{prefix}/")));
            let _ = writeln!(out, "    mapped_srcs = {mapped}{},", foreign.map(|foreign| format!(" | {foreign}")).unwrap_or_default());
        }
        (None, foreign) => {
            let _ = writeln!(out, "    srcs = {files},");
            if let Some(foreign) = foreign {
                let _ = writeln!(out, "    mapped_srcs = {foreign},");
            }
        }
    }
}

fn inline(items: &[String]) -> String {
    format!("[{}]", items.iter().map(|item| quote(item)).collect::<Vec<_>>().join(", "))
}

fn list(items: &[String], depth: usize) -> String {
    let indent = "    ".repeat(depth);
    let mut out = "[\n".to_owned();
    for item in items {
        let _ = writeln!(out, "{indent}    {},", quote(item));
    }
    out.push_str(&indent);
    out.push(']');
    out
}

fn dict<'a>(entries: impl Iterator<Item = (&'a String, &'a String)>, depth: usize) -> String {
    let indent = "    ".repeat(depth);
    let mut out = "{\n".to_owned();
    for (key, value) in entries {
        let _ = writeln!(out, "{indent}    {}: {},", quote(key), quote(value));
    }
    out.push_str(&indent);
    out.push('}');
    out
}

fn quote(text: &str) -> String {
    format!("\"{}\"", text.replace('\\', "\\\\").replace('"', "\\\""))
}

fn files(out: &mut String, root: bool) {
    let patterns: Vec<String> = FILES.iter().map(|pattern| (*pattern).to_owned()).collect();
    let excludes: Vec<String> = ROOT_EXCLUDES.iter().map(|path| (*path).to_owned()).collect();
    let srcs = if root { format!("glob({}, exclude = {})", inline(&patterns), inline(&excludes)) } else { format!("glob({})", inline(&patterns)) };
    let _ = writeln!(out, "north_files(\n    name = \"files\",\n    srcs = {srcs},\n    visibility = [\"PUBLIC\"],\n)");
}
