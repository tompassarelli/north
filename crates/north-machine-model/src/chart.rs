use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::time::Duration;

use super::{Arrow, Facts, Model};

fn alias(name: &str) -> String {
    name.replace('-', "_")
}

fn span(dwell: Duration) -> String {
    match dwell.as_secs() {
        seconds if seconds >= 3600 && seconds % 3600 == 0 => format!("{} h", seconds / 3600),
        seconds if seconds >= 60 && seconds % 60 == 0 => format!("{} min", seconds / 60),
        seconds => format!("{seconds} s"),
    }
}

fn listed(states: &[Facts], keep: impl Fn(&Facts) -> Option<String>) -> String {
    let named: Vec<String> = states.iter().filter_map(keep).collect();
    if named.is_empty() { "none".to_owned() } else { named.join(", ") }
}

fn diagram(model: &Model) -> String {
    let mut out = String::from("stateDiagram-v2\n");
    for state in model.states.iter().filter(|state| state.name.contains('-')) {
        let _ = writeln!(out, "    state \"{}\" as {}", state.name, alias(state.name));
    }
    let mut arrows: BTreeMap<(Option<&str>, &str), Vec<&Arrow>> = BTreeMap::new();
    for moved in &model.moves {
        arrows.entry((moved.from, moved.to)).or_default().push(&moved.arrow);
    }
    for ((from, to), kinds) in arrows {
        let mut labels = Vec::new();
        if kinds.contains(&&Arrow::HolderGone) {
            labels.push("holder gone");
        }
        if kinds.contains(&&Arrow::Replaces) {
            labels.push(if kinds.contains(&&Arrow::Writer) { "also from a live holder" } else { "from a live holder" });
        }
        let label = if labels.is_empty() { String::new() } else { format!(": {}", labels.join(", ")) };
        let _ = writeln!(out, "    {} --> {}{label}", from.map_or_else(|| "[*]".to_owned(), alias), alias(to));
    }
    for state in model.states.iter().filter(|state| state.end) {
        let _ = writeln!(out, "    {} --> [*]", alias(state.name));
    }
    out
}

/// The machine's page: a Mermaid state chart of every move the store accepted while the machine was explored, with
/// the scope and the promises it was checked against. `source` is the file holding the machine's table.
pub fn page(model: &Model, source: &str) -> String {
    let states = &model.states;
    format!(
        "# {machine} state chart\n\n\
         Generated by `north check machines --write` from the table in `{source}`, driven through the lifecycle store;\n\
         do not edit. The landing refuses a page that differs from what the check generates.\n\n\
         ```mermaid\n{diagram}```\n\n\
         - Checked: {situations} situations and {steps} steps, every ordering of three processes (two on one host, one on\n  \
           another) that each try every move for every holder and settle the instance, the death of the process holding\n  \
           the state, and its dwell running out.\n\
         - Held by a process, and left when that process is gone: {held}.\n\
         - Dwell: {dwell}.\n\
         - Ends, which an instance never leaves: {ends}.\n\
         - May be announced again: {repeats}.\n\
         - Promises checked: every accepted move is logged and the log alone rebuilds the record; a held state is taken\n  \
           from a live holder only by a move the machine lets replace one; an end has no way out, no dwell and no\n  \
           holder; a repeat is accepted exactly where promised; every other situation can be left once nothing more\n  \
           dies; every state is reached.\n",
        machine = model.machine,
        diagram = diagram(model),
        situations = model.situations,
        steps = model.steps,
        held = listed(states, |state| state.held.then(|| state.name.to_owned())),
        dwell = listed(states, |state| state.dwell.map(|dwell| format!("{} {}", state.name, span(dwell)))),
        ends = listed(states, |state| state.end.then(|| state.name.to_owned())),
        repeats = listed(states, |state| state.repeats.then(|| state.name.to_owned())),
    )
}
